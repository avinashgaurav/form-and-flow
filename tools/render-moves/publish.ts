// Copies the rendered clips into the app and writes the lookup the app imports.
// Run after rendering: npx tsx tools/render-moves/publish.ts
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { EXERCISES } from '@ff/engines';

const ROOT = join(import.meta.dirname, '..', '..');
const FROM = join(ROOT, 'media-src', 'renders');
const TO = join(ROOT, 'app', 'assets', 'exercises');
const MAX_BYTES = 1.5 * 1024 * 1024; // plan/09: each loop under 1.5 MB
const MIN_BYTES = 10 * 1024; // anything smaller is a broken or empty render

// A clip must be a whole, square H.264 video, not a file still being written.
function check(id: string, file: string): void {
  const bytes = statSync(file).size;
  if (bytes > MAX_BYTES) throw new Error(`${id}.mp4 is ${bytes} bytes, over the 1.5 MB limit`);
  if (bytes < MIN_BYTES) throw new Error(`${id}.mp4 is only ${bytes} bytes`);
  const probe = spawnSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=codec_name,width,height', '-of', 'csv=p=0', file], { encoding: 'utf8' });
  if (probe.error) throw new Error(`ffprobe could not run (is ffmpeg installed?): ${probe.error.message}`);
  const [codec, w, h] = probe.stdout.trim().split(',');
  if (probe.status !== 0 || codec !== 'h264' || w !== h || !w) throw new Error(`${id}.mp4 is not a valid square H.264 clip: ${probe.stderr || probe.stdout}`);
}

mkdirSync(TO, { recursive: true });
const have: string[] = [];
const missing: string[] = [];
for (const e of EXERCISES) {
  const src = join(FROM, `${e.id}.mp4`);
  if (!existsSync(src)) {
    missing.push(e.id);
    continue;
  }
  check(e.id, src);
  copyFileSync(src, join(TO, `${e.id}.mp4`));
  have.push(e.id);
}

const lines = have.map((id) => `  ${id}: require('../../assets/exercises/${id}.mp4'),`);
writeFileSync(
  join(ROOT, 'app', 'src', 'media', 'exerciseVideos.ts'),
  `// Generated by tools/render-moves/publish.ts from media-src/renders. Do not edit by hand.
// 3D demos: a Mixamo character (Adobe, royalty free) moved by Mixamo motion capture or by our
// own keyframes. Licence notes: plan/25-exercise-media-sources.md.
/* eslint-disable @typescript-eslint/no-require-imports */
const VIDEOS: Record<string, number> = {
${lines.join('\n')}
};

/** The looping demo for an exercise, if there is one. */
export function exerciseVideo(exerciseId: string): number | undefined {
  return VIDEOS[exerciseId];
}
`,
);
console.log(`published ${have.length} clips${missing.length ? `; missing: ${missing.join(', ')}` : ''}`);
